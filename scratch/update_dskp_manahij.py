def update_dskp_master():
    csv_path = 'data-rujukan/dskp_master.csv'
    if not os.path.exists(csv_path):
        print(f"File {csv_path} not found!")
        return

    # Backup original file first
    backup_path = 'data-rujukan/dskp_master.csv.bak'
    if not os.path.exists(backup_path):
        import shutil
        shutil.copyfile(csv_path, backup_path)
        print(f"Created backup at {backup_path}")

    # Read all lines
    with open(csv_path, 'r', encoding='utf-8', errors='ignore') as f:
        reader = list(csv.reader(f))

    header = reader[0]
    non_manahij_rows_before = []
    non_manahij_rows_after = []
    seen_manahij = False
    passed_manahij = False

    for r in reader[1:]:
        if not r or not r[0].strip():
            continue
        subj = r[0].strip()
        if 'مناهج العلوم الإسلامية' in subj:
            seen_manahij = True
        else:
            if not seen_manahij:
                non_manahij_rows_before.append(r)
            else:
                passed_manahij = True
                non_manahij_rows_after.append(r)

    print(f"Before manahij: {len(non_manahij_rows_before)} rows")
    print(f"After manahij: {len(non_manahij_rows_after)} rows")

    new_manahij_rows = build_manahij_rows()
    print(f"Generated new manahij rows: {len(new_manahij_rows)} rows")

    final_rows = [header] + non_manahij_rows_before + new_manahij_rows + non_manahij_rows_after

    with open(csv_path, 'w', encoding='utf-8', newline='') as f:
        writer = csv.writer(f)
        writer.writerows(final_rows)

    print(f"Successfully updated {csv_path} with {len(final_rows)} total rows!")

if __name__ == '__main__':
    update_dskp_master()
